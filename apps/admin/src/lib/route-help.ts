/**
 * Resolve help content for a pathname: exact match first, then pattern
 * match against `:param` segments (`/orders/42` ↔ `/orders/:id`).
 */
export function resolveRouteHelp(pathname: string): RouteHelpEntry | null {
  const path = pathname.length > 1 && pathname.endsWith('/') ? pathname.slice(0, -1) : pathname
  if (ROUTE_HELP[path]) {
    return ROUTE_HELP[path]
  }
  const segments = path.split('/')
  for (const [pattern, help] of Object.entries(ROUTE_HELP)) {
    const parts = pattern.split('/')
    if (parts.length !== segments.length) {
      continue
    }
    const matches = parts.every(
      (part, index) => part.startsWith(':') || part === segments[index],
    )
    if (matches) {
      return help
    }
  }
  return null
}
