/**
 * Contextual route help registry (SS-269). ONE typed, centralized source for
 * the Persian help content of every admin route — no scattered hardcoded
 * text in pages. PageHeader resolves the current pathname against this
 * registry automatically; detail pages with custom headings mount the
 * standalone `RouteHelpButton` instead.
 *
 * Dynamic routes are keyed with `:param` segments; `resolveRouteHelp`
 * matches them against the live pathname.
 */

export interface RouteHelpSection {
  heading: string
  body: string
}

export interface RouteHelpEntry {
  /** Panel title (defaults to the page title when omitted in callers). */
  title: string
  /** One-paragraph answer to «این صفحه برای چیست؟». */
  summary: string
  /** What the main sections/data represent and what the controls do. */
  sections: RouteHelpSection[]
  /** Step-by-step outline for the page's most important workflow, if any. */
  workflows?: string[]
}

function entry(
  title: string,
  summary: string,
  sections: RouteHelpSection[],
  workflows?: string[],
): RouteHelpEntry {
  return { title, summary, sections, workflows }
}

